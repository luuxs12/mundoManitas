-- =====================================================================
-- V6: funciones comunitarias del aula.
--
-- Agrega tres tablas independientes del contenido educativo:
--   * favorito: cursos guardados por cada estudiante.
--   * resena:   opinión de un estudiante sobre un curso que ya cursa.
--   * anuncio:  comunicados del docente para los alumnos del curso.
--
-- Las restricciones únicas evitan duplicados y las claves foráneas
-- mantienen la integridad con usuario y modulo.
-- =====================================================================

CREATE TABLE IF NOT EXISTS favorito (
    idfavorito    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idestudiante  integer   NOT NULL,
    idmodulo      integer   NOT NULL,
    fechacreacion timestamp NOT NULL,
    CONSTRAINT uk_favorito_estudiante_modulo UNIQUE (idestudiante, idmodulo),
    CONSTRAINT fk_favorito_estudiante FOREIGN KEY (idestudiante) REFERENCES usuario (idusuario),
    CONSTRAINT fk_favorito_modulo FOREIGN KEY (idmodulo) REFERENCES modulo (idmodulo)
);

CREATE INDEX IF NOT EXISTS idx_favorito_estudiante ON favorito (idestudiante);
CREATE INDEX IF NOT EXISTS idx_favorito_modulo ON favorito (idmodulo);

CREATE TABLE IF NOT EXISTS resena (
    idresena           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idestudiante       integer      NOT NULL,
    idmodulo           integer      NOT NULL,
    calificacion       integer      NOT NULL,
    comentario         varchar(500) NOT NULL,
    fechacreacion      timestamp    NOT NULL,
    fechaactualizacion timestamp,
    CONSTRAINT uk_resena_estudiante_modulo UNIQUE (idestudiante, idmodulo),
    CONSTRAINT fk_resena_estudiante FOREIGN KEY (idestudiante) REFERENCES usuario (idusuario),
    CONSTRAINT fk_resena_modulo FOREIGN KEY (idmodulo) REFERENCES modulo (idmodulo),
    CONSTRAINT ck_resena_calificacion CHECK (calificacion BETWEEN 1 AND 5)
);

CREATE INDEX IF NOT EXISTS idx_resena_modulo ON resena (idmodulo);
CREATE INDEX IF NOT EXISTS idx_resena_estudiante ON resena (idestudiante);

CREATE TABLE IF NOT EXISTS anuncio (
    idanuncio        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idmodulo         integer       NOT NULL,
    iddocente        integer       NOT NULL,
    titulo           varchar(120)  NOT NULL,
    mensaje          varchar(1000) NOT NULL,
    fechapublicacion timestamp     NOT NULL,
    activo           boolean       NOT NULL DEFAULT true,
    CONSTRAINT fk_anuncio_modulo FOREIGN KEY (idmodulo) REFERENCES modulo (idmodulo),
    CONSTRAINT fk_anuncio_docente FOREIGN KEY (iddocente) REFERENCES usuario (idusuario)
);

CREATE INDEX IF NOT EXISTS idx_anuncio_modulo ON anuncio (idmodulo, activo);
CREATE INDEX IF NOT EXISTS idx_anuncio_docente ON anuncio (iddocente);
