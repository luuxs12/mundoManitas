-- =====================================================================
-- V5: Cursos premium y compras simuladas.
--
-- Un módulo puede marcarse como premium y llevar un precio. El estudiante
-- "compra" el curso desde la plataforma; la compra queda registrada en la
-- tabla compra y habilita el contenido. No se integra una pasarela real:
-- el pago es simulado y auditables todos sus datos.
-- =====================================================================

ALTER TABLE modulo ADD COLUMN IF NOT EXISTS premium boolean NOT NULL DEFAULT false;
ALTER TABLE modulo ADD COLUMN IF NOT EXISTS precio numeric(10, 2) NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS compra (
    idcompra      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idestudiante  integer        NOT NULL,
    idmodulo      integer        NOT NULL,
    monto         numeric(10, 2) NOT NULL,
    estado        varchar(20)    NOT NULL DEFAULT 'PAGADA',
    referencia    varchar(60)    NOT NULL,
    metodopago    varchar(30)    NOT NULL DEFAULT 'SIMULADO',
    fechacompra   timestamp      NOT NULL,
    CONSTRAINT uk_compra_estudiante_modulo UNIQUE (idestudiante, idmodulo),
    CONSTRAINT fk_compra_estudiante FOREIGN KEY (idestudiante) REFERENCES usuario (idusuario),
    CONSTRAINT fk_compra_modulo FOREIGN KEY (idmodulo) REFERENCES modulo (idmodulo)
);

CREATE INDEX IF NOT EXISTS idx_compra_estudiante ON compra (idestudiante);
CREATE INDEX IF NOT EXISTS idx_compra_modulo ON compra (idmodulo);
CREATE INDEX IF NOT EXISTS idx_modulo_premium ON modulo (premium);

