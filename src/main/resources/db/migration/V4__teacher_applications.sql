-- =====================================================================
-- V4: Postulaciones de docentes.
--
-- El docente no se registra libremente: envía su portafolio, acredita su
-- dominio de Lengua de Señas Peruana (LSP) y su experiencia en TI. El
-- administrador revisa la postulación y, si la aprueba, crea la cuenta
-- DOCENTE y le asigna un módulo educativo.
-- =====================================================================

CREATE TABLE IF NOT EXISTS postulacion_docente (
    idpostulacion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(100) NOT NULL,
    email varchar(100) NOT NULL,
    telefono varchar(20) NOT NULL,
    nivellsp varchar(10) NOT NULL,
    certificacionlsp varchar(200) NOT NULL,
    aniosexperiencia integer NOT NULL,
    areati varchar(120) NOT NULL,
    portafolio varchar(300) NOT NULL,
    motivacion text NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'PENDIENTE',
    observacion text,
    fechapostulacion timestamp NOT NULL,
    fecharesolucion timestamp,
    idusuario integer,
    idmodulo integer,
    CONSTRAINT fk_postulacion_usuario FOREIGN KEY (idusuario) REFERENCES usuario (idusuario),
    CONSTRAINT fk_postulacion_modulo FOREIGN KEY (idmodulo) REFERENCES modulo (idmodulo)
);

CREATE INDEX IF NOT EXISTS idx_postulacion_estado ON postulacion_docente (estado);
CREATE INDEX IF NOT EXISTS idx_postulacion_email ON postulacion_docente (email);
